'use strict';
// Writes docs/JAPANESE_WORDING_REVIEW.md: every panel text in English and Japanese side by side, for a native speaker to review.
// Usage: node scripts/export-wording-sheet.js
const fs = require('node:fs');
const path = require('node:path');
const { MESSAGES, FINDING_TEXT } = require('../src/report');

const cell = value => String(value).replace(/\|/g, '\|').replace(/\r?\n/g, ' ');
const rows = ['| Key | English | Japanese | OK? / suggested wording |', '|---|---|---|---|'];
for (const key of Object.keys(MESSAGES.en)) rows.push(`| \`${key}\` | ${cell(MESSAGES.en[key])} | ${cell(MESSAGES.ja[key])} | |`);
const findingRows = ['| Rule | Field | Japanese | OK? / suggested wording |', '|---|---|---|---|'];
for (const [rule, fields] of Object.entries(FINDING_TEXT.ja)) for (const [field, value] of Object.entries(fields)) findingRows.push(`| \`${rule}\` | ${field} | ${cell(value)} | |`);
const text = `# Japanese wording review sheet (Audio Preflight 0.3.0)

Generated by \`node scripts/export-wording-sheet.js\`. Do not edit the tables by hand: edit \`src/report.js\` and regenerate.
The Japanese below has NOT been reviewed by a native speaker. Please mark each row OK or write a better wording.
\`{name}\` style words are filled in by the panel; keep them unchanged. Tone to aim for: plain, polite (です／ます), short.

## Panel and report texts

${rows.join('\n')}

## Finding texts (Japanese only; the English originals are in \`src/diagnostics.js\`)

${findingRows.join('\n')}
`;
fs.writeFileSync(path.join(__dirname, '../docs/JAPANESE_WORDING_REVIEW.md'), text);
console.log('wrote docs/JAPANESE_WORDING_REVIEW.md with', Object.keys(MESSAGES.en).length, 'texts and', findingRows.length - 2, 'finding texts');
